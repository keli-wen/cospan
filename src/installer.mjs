function writeCleanDirFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

function writeTargetReferences(skillDir, targetId, hostMode, cospanBin) {
  if (targetId === 'codex') {
    writeCleanDirFile(
      path.join(skillDir, 'references', 'draw.md'),
      renderCodexDrawReference({ hostMode, cospanBin })
    );
  } else if (targetId === 'grok') {
    writeCleanDirFile(
      path.join(skillDir, 'references', 'live-search.md'),
      renderGrokSearchReference({ hostMode, cospanBin })
    );
  }
}

/**
 * Install the Antigravity (`agy`) plugin bundle into `~/.gemini/config/plugins/cospan/`.
 */
export function installForAgyHost({
  discovered,
  force = false,
  cospanBin = COSPAN_BIN_PATH,
  pluginsRoot = process.env.COSPAN_AGY_PLUGINS_DIR ||
    path.join(os.homedir(), '.gemini', 'config', 'plugins'),
}) {
  const pluginDir = path.join(pluginsRoot, 'cospan');
  const skillsRoot = path.join(pluginDir, 'skills');
  fs.rmSync(skillsRoot, { recursive: true, force: true });
  fs.mkdirSync(skillsRoot, { recursive: true });

  const mountedTargets = [];
  for (const targetId of MOUNTABLE_TARGET_IDS) {
    if (force || discovered[targetId]?.installed) {
      mountedTargets.push(targetId);
      const skillDir = path.join(skillsRoot, `cospan-${targetId}`);
      writeCleanDirFile(
        path.join(skillDir, 'SKILL.md'),
        renderAgyHostTargetSkill({ targetId, cospanBin })
      );
      writeTargetReferences(skillDir, targetId, 'agy', cospanBin);
    }
  }

  writeCleanDirFile(
    path.join(skillsRoot, 'cospan-jobs', 'SKILL.md'),
    renderAgyHostJobsSkill({ cospanBin })
  );

  const sidecarsRoot = path.join(pluginDir, 'sidecars');
  fs.rmSync(sidecarsRoot, { recursive: true, force: true });
  const sidecarPath = path.join(sidecarsRoot, 'cospan_board', 'sidecar.json');
  writeCleanDirFile(sidecarPath, JSON.stringify(renderAgySidecarManifest(), null, 2) + '\n');

  const srcIconSvg = path.join(PACKAGE_ROOT, 'assets', 'icon.svg');
  const hasIconSvg = fs.existsSync(srcIconSvg);
  if (hasIconSvg) {
    fs.mkdirSync(path.join(pluginDir, 'assets'), { recursive: true });
    fs.copyFileSync(srcIconSvg, path.join(pluginDir, 'assets', 'icon.svg'));
  }

  const manifest = {
    name: 'cospan',
    displayName: 'Cospan',
    version: PACKAGE_VERSION,
    description:
      'Persona-free point-to-point headless delegation primitive across ' +
      'Antigravity (agy), OpenAI Codex, Claude Code, DeepSeek Harness (dsh), and Grok Build.',
    ...(hasIconSvg ? { logo: 'assets/icon.svg' } : {}),
    author: 'Keli Wen',
    repository: 'https://github.com/keli-wen/cospan',
    suggestedPrompts: [
      'Use cospan-codex in --readonly mode to review our current git diff',
      'Use cospan-agy with --model hydrogen --effort xhigh to review this design',
      'Continue the latest cospan job with a follow-up question',
    ],
  };
  writeCleanDirFile(path.join(pluginDir, 'plugin.json'), JSON.stringify(manifest, null, 2) + '\n');
  writeCleanDirFile(
    path.join(pluginDir, 'README.md'),
    `# Cospan (Antigravity Host Bundle)\n\nGenerated by \`cospan install\`. Provides:\n` +
      mountedTargets.map((t) => `- \`cospan-${t}\`\n`).join('') +
      `- \`cospan-jobs\` (internal)\n`
  );

  return {
    host: 'agy',
    pluginDir,
    sidecar: sidecarPath,
    skills: [...mountedTargets.map((t) => `cospan-${t}`), 'cospan-jobs'],
  };
}

function copyPluginAssets(destRoot) {
  const srcAssetsDir = path.join(PACKAGE_ROOT, 'assets');
  const destAssetsDir = path.join(destRoot, 'assets');
  const copied = { svg: false, png128: false };
  for (const [key, filename] of [
    ['svg', 'icon.svg'],
    ['png128', 'icon-128.png'],
  ]) {
    const src = path.resolve(srcAssetsDir, filename);
    if (!fs.existsSync(src)) continue;
    fs.mkdirSync(destAssetsDir, { recursive: true });
    const dst = path.resolve(destAssetsDir, filename);
    if (src !== dst) fs.copyFileSync(src, dst);
    copied[key] = true;
  }
  return copied;
}

function writeCodexBundleAtRoot({
  bundleRoot,
  discovered,
  force,
  cospanBin,
  mcpCommand = 'node',
  mcpArgs = ['${PLUGIN_ROOT}/src/mcp/cospan-mcp.mjs'],
}) {
  const skillsRoot = path.join(bundleRoot, 'skills');
  fs.rmSync(skillsRoot, { recursive: true, force: true });
  fs.mkdirSync(skillsRoot, { recursive: true });

  const mountedTargets = [];
  for (const targetId of MOUNTABLE_TARGET_IDS) {
    if (force || discovered[targetId]?.installed) {
      mountedTargets.push(targetId);
      const skillDir = path.join(skillsRoot, targetId);
      writeCleanDirFile(
        path.join(skillDir, 'SKILL.md'),
        renderCodexHostTargetSkill({ targetId, cospanBin })
      );
      writeTargetReferences(skillDir, targetId, 'mcp', cospanBin);
    }
  }
  writeCleanDirFile(path.join(skillsRoot, 'jobs', 'SKILL.md'), renderCodexHostJobsSkill());

  const assets = copyPluginAssets(bundleRoot);

  const codexManifest = {
    name: 'cospan',
    version: PACKAGE_VERSION,
    description:
      'Persona-free point-to-point headless delegation primitive for Codex ' +
      '($cospan:agy, $cospan:codex, $cospan:claude, $cospan:dsh, $cospan:grok + cospan MCP).',
    keywords: (
      'cospan orchestration multi-agent coding-agent subagents code-review mcp ' +
      'agent-skills agy antigravity codex claude-code deepseek-harness dsh grok ' +
      'multi-harness delegation'
    ).split(' '),
    skills: './skills/',
    mcpServers: './.mcp.json',
    interface: {
      displayName: 'Cospan',
      shortDescription:
        'Delegate tasks point-to-point to headless harnesses across ' +
        'Antigravity, Codex, Claude Code, DeepSeek Harness, and Grok Build.',
      developerName: 'Keli Wen',
      category: 'Developer Tools',
      capabilities: ['Skills', 'MCP'],
      ...(assets.svg ? { composerIcon: './assets/icon.svg' } : {}),
      ...(assets.png128 ? { logo: './assets/icon-128.png' } : {}),
      defaultPrompt: [
        'Use $cospan:agy in readonly mode to analyze this module',
        'Use $cospan:codex with explicit model/effort for a detached review',
      ],
    },
  };
  writeCleanDirFile(
    path.join(bundleRoot, '.codex-plugin', 'plugin.json'),
    JSON.stringify(codexManifest, null, 2) + '\n'
  );

  const mcpJson = {
    $schema: 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json',
    mcpServers: {
      cospan: {
        type: 'stdio',
        command: mcpCommand,
        ...(mcpArgs.length ? { args: mcpArgs } : {}),
      },
    },
  };
  writeCleanDirFile(path.join(bundleRoot, '.mcp.json'), JSON.stringify(mcpJson, null, 2) + '\n');
  return mountedTargets;
}

function copyMarketplaceMcpFiles({ packageRoot, marketPluginRoot, cospanBin, useLauncher }) {
  const pkgMcpDir = path.join(packageRoot, 'src', 'mcp');
  const fallbackMcpDir = path.join(PACKAGE_ROOT, 'src', 'mcp');
  const names = new Set([
    ...(fs.existsSync(fallbackMcpDir)
      ? fs.readdirSync(fallbackMcpDir).filter((f) => f.endsWith('.mjs'))
      : []),
    ...(fs.existsSync(pkgMcpDir)
      ? fs.readdirSync(pkgMcpDir).filter((f) => f.endsWith('.mjs'))
      : []),
  ]);
  for (const name of names) {
    const primary = path.join(pkgMcpDir, name);
    const srcPath = fs.existsSync(primary) ? primary : path.join(fallbackMcpDir, name);
    writeCleanDirFile(path.join(marketPluginRoot, 'mcp', name), fs.readFileSync(srcPath, 'utf8'));
  }
  writeCleanDirFile(
    path.join(marketPluginRoot, 'mcp', 'cospan-runtime.json'),
    JSON.stringify({ cospanBin }, null, 2) + '\n'
  );
  if (useLauncher) {
    const launcherPath = path.join(marketPluginRoot, 'mcp', 'run-mcp.sh');
    writeCleanDirFile(
      launcherPath,
      `#!/bin/sh\nexec "${process.execPath}" "$(dirname "$0")/cospan-mcp.mjs"\n`
    );
    fs.chmodSync(launcherPath, 0o755);
  }
}

function runCodexPluginCmd(codexBin, subArgs, timeout) {
  const spawnCmd = buildSpawnCommand(codexBin, subArgs);
  return spawnSync(spawnCmd.cmd, spawnCmd.args, {
    encoding: 'utf8',
    timeout,
    windowsHide: true,
    windowsVerbatimArguments: Boolean(spawnCmd.windowsVerbatimArguments),
  });
}

function registerCodexLocalMarketplace(codexBin, marketplaceRoot) {
  const registration = { attempted: true, ok: false, details: [] };
  runCodexPluginCmd(
    codexBin,
    ['--enable', 'plugins', 'plugin', 'remove', 'cospan@cospan-local'],
    10000
  );
  runCodexPluginCmd(
    codexBin,
    ['--enable', 'plugins', 'plugin', 'marketplace', 'remove', 'cospan-local'],
    10000
  );
  const mAdd = runCodexPluginCmd(
    codexBin,
    ['--enable', 'plugins', 'plugin', 'marketplace', 'add', marketplaceRoot],
    15000
  );
  registration.details.push({
    step: 'marketplace_add',
    status: mAdd.status,
    stdout: (mAdd.stdout || '').trim(),
    stderr: (mAdd.stderr || '').trim(),
  });
  const pAdd = runCodexPluginCmd(
    codexBin,
    ['--enable', 'plugins', 'plugin', 'add', 'cospan@cospan-local'],
    15000
  );
  registration.details.push({
    step: 'plugin_add',
    status: pAdd.status,
    stdout: (pAdd.stdout || '').trim(),
    stderr: (pAdd.stderr || '').trim(),
  });
  registration.ok = mAdd.status === 0 && pAdd.status === 0;
  return registration;
}

/**
 * Generate the Codex plugin bundle in `packageRoot` and local marketplace
 * (`~/.cospan/codex-marketplace`).
 */
export function installForCodexHost({
  discovered,
  force = false,
  cospanBin = COSPAN_BIN_PATH,
  registerWithCodexCli = true,
  packageRoot = PACKAGE_ROOT,
  marketplaceRoot = process.env.COSPAN_CODEX_MARKETPLACE_DIR ||
    path.join(cospanHomeDir(), 'codex-marketplace'),
}) {
  const mountedTargets = writeCodexBundleAtRoot({
    bundleRoot: packageRoot,
    discovered,
    force,
    cospanBin: '<skill-dir>/../../bin/cospan.mjs',
    mcpCommand: 'node',
    mcpArgs: ['${PLUGIN_ROOT}/src/mcp/cospan-mcp.mjs'],
  });

  const marketPluginRoot = path.join(marketplaceRoot, 'plugins', 'cospan');
  fs.rmSync(marketPluginRoot, { recursive: true, force: true });
  fs.mkdirSync(marketPluginRoot, { recursive: true });
  const useLauncher = process.platform !== 'win32';
  writeCodexBundleAtRoot({
    bundleRoot: marketPluginRoot,
    discovered,
    force,
    cospanBin,
    mcpCommand: useLauncher ? './mcp/run-mcp.sh' : 'node',
    mcpArgs: useLauncher ? [] : ['${PLUGIN_ROOT}/mcp/cospan-mcp.mjs'],
  });
  copyMarketplaceMcpFiles({ packageRoot, marketPluginRoot, cospanBin, useLauncher });

  const marketplaceManifest = {
    name: 'cospan-local',
    plugins: [{ name: 'cospan', source: { source: 'local', path: './plugins/cospan' } }],
  };
  writeCleanDirFile(
    path.join(marketplaceRoot, '.agents', 'plugins', 'marketplace.json'),
    JSON.stringify(marketplaceManifest, null, 2) + '\n'
  );

  const codexBin = discovered.codex?.binary;
  const registration =
    registerWithCodexCli && codexBin
      ? registerCodexLocalMarketplace(codexBin, marketplaceRoot)
      : { attempted: false, ok: false, details: [] };

  return {
    host: 'codex',
    packageRoot,
    marketplaceRoot,
    skills: [...mountedTargets.map((t) => `$cospan:${t}`), 'cospan:jobs'],
    registration,
  };
}

export function runInstall({ host = 'all', force = false, registerWithCodexCli = true } = {}) {
  try {
    syncDshClient();
  } catch {}
  const configFile = ensureDefaultGlobalConfig();
  const discovered = discoverAllTargets();
  const pinned = {};
  for (const [id, info] of Object.entries(discovered)) {
    if (info.installed && info.binary) {
      pinned[id] = { binary: info.binary, version: info.version, phase: info.phase };
    }
  }
  const targetsPath = savePinnedTargets(pinned);

  const results = [];
  if (host === 'all' || host === 'agy') {
    results.push(installForAgyHost({ discovered, force }));
  }
  if (host === 'all' || host === 'codex') {
    results.push(installForCodexHost({ discovered, force, registerWithCodexCli }));
  }
  return { configFile, targetsPath, discovered, results };
}
