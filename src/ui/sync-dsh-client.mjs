import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UI_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(UI_DIR, '..', '..');

const BOARD_CSS_PATH = path.join(UI_DIR, 'cospan-board.css');
const BOARD_JS_PATH = path.join(UI_DIR, 'cospan-board.js');
const DSH_BRIDGE_PATH = path.join(REPO_ROOT, 'dsh', 'client-bridge.js');
const DSH_CLIENT_PATH = path.join(REPO_ROOT, 'dsh', 'client.js');

function escapeTemplateLiteral(raw) {
  return raw.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
}

function normalizeLf(raw) {
  return raw.replace(/\r\n/g, '\n');
}

function indentJsBlock(rawJs, spaces = 4) {
  const pad = ' '.repeat(spaces);
  const cleaned = normalizeLf(rawJs)
    .replace(/^\/\* global [^\n]*\*\/\n/, '')
    .replace(/\n*if \(typeof globalThis !== 'undefined'\) \{\n[\s\S]*?\}\s*$/, '')
    .trimEnd();
  const indented = cleaned
    .split('\n')
    .map((line) => (line.length > 0 ? `${pad}${line}` : ''))
    .join('\n');
  return `${pad}// prettier-ignore\n${indented}`;
}

export function buildDshClientBundle() {
  const css = normalizeLf(fs.readFileSync(BOARD_CSS_PATH, 'utf8')).trim();
  const boardJs = normalizeLf(fs.readFileSync(BOARD_JS_PATH, 'utf8'));
  const bridge = normalizeLf(fs.readFileSync(DSH_BRIDGE_PATH, 'utf8'));

  const cssMarker = "'__COSPAN_BOARD_CSS_PLACEHOLDER__'";
  if (!bridge.includes(cssMarker)) {
    throw new Error('Missing CSS injection marker in dsh/client-bridge.js');
  }
  const jsMarkerRe = / {4}\/\* __COSPAN_JS_START__ \*\/[\s\S]*?\/\* __COSPAN_JS_END__ \*\//;
  if (!jsMarkerRe.test(bridge)) {
    throw new Error('Missing JS injection marker in dsh/client-bridge.js');
  }

  const withCss = bridge.replace(cssMarker, `\`\n${escapeTemplateLiteral(css)}\n\``);
  const withJs = withCss.replace(jsMarkerRe, () => indentJsBlock(boardJs, 4));
  const withGlobals = withJs.replace(
    /^\/\* global [^\n]*\*\//,
    '/* global window, document, navigator, localStorage, fetch, IntersectionObserver, ' +
      'setTimeout, clearTimeout, setInterval, clearInterval */'
  );
  return `// Generated by src/ui/sync-dsh-client.mjs — do not edit directly.\n${withGlobals}`;
}

export function syncDshClient({ outputPath = DSH_CLIENT_PATH, write = true } = {}) {
  const content = buildDshClientBundle();
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
  const changed = existing !== content;
  if (write && changed) {
    fs.writeFileSync(outputPath, content, 'utf8');
  }
  return { outputPath, content, changed };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const res = syncDshClient();
  process.stdout.write(
    `${res.changed ? 'Synced' : 'Up-to-date'}: ${path.relative(REPO_ROOT, res.outputPath)}\n`
  );
}
